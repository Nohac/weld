//! Input preferences and modifier contracts shared by configuration and native hosts.

use std::num::NonZeroU32;
/// XKB rules, model, layout, variant and options selected by configuration.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct KeymapConfig {
    pub rules: String,
    pub model: String,
    pub layout: String,
    pub variant: String,
    pub options: String,
}

impl Default for KeymapConfig {
    fn default() -> Self {
        Self {
            rules: String::new(),
            model: String::new(),
            layout: "us".into(),
            variant: String::new(),
            options: String::new(),
        }
    }
}

/// Scope of one physical-device preference rule.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum InputDeviceSelector {
    All,
    Touchpad,
    Identifier(String),
}

/// Buttons generated by one-, two-, and three-finger taps.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FingerButtonMap {
    LeftRightMiddle,
    LeftMiddleRight,
}

/// Software button behavior for touchpad clicks.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum TouchpadClickMethod {
    None,
    ButtonAreas,
    Clickfinger,
}

/// Omitted fields use the device's native defaults.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct TouchpadPreferences {
    pub tap: Option<bool>,
    pub tap_button_map: Option<FingerButtonMap>,
    pub click_method: Option<TouchpadClickMethod>,
}

impl TouchpadPreferences {
    fn overlay(&mut self, other: Self) {
        self.tap = other.tap.or(self.tap);
        self.tap_button_map = other.tap_button_map.or(self.tap_button_map);
        self.click_method = other.click_method.or(self.click_method);
    }
}

/// A selector and the fields it overrides.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PointerDeviceRule {
    pub selector: InputDeviceSelector,
    pub preferences: TouchpadPreferences,
}

/// Complete configuration; exact device rules override type rules and wildcard rules.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
#[cfg_attr(feature = "ecs", derive(bevy_ecs::resource::Resource))]
pub struct PointerDeviceSettings(pub Vec<PointerDeviceRule>);

impl PointerDeviceSettings {
    /// Resolve matching rules in specificity order, then declaration order.
    pub fn resolve(&self, identifier: &str, touchpad: bool) -> TouchpadPreferences {
        let mut result = TouchpadPreferences::default();
        for priority in 0..3 {
            for rule in &self.0 {
                let matched = match &rule.selector {
                    InputDeviceSelector::All => priority == 0,
                    InputDeviceSelector::Touchpad => priority == 1 && touchpad,
                    InputDeviceSelector::Identifier(value) => priority == 2 && value == identifier,
                };
                if matched {
                    result.overlay(rule.preferences);
                }
            }
        }
        result
    }
}

/// Cursor artwork preference; an omitted size preserves the assembly's default.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CursorThemeSettings {
    pub theme: String,
    pub size: Option<NonZeroU32>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn specific_rules_overlay_individual_fields_and_removal_restores_defaults() {
        let settings = PointerDeviceSettings(vec![
            PointerDeviceRule {
                selector: InputDeviceSelector::Identifier("pad".into()),
                preferences: TouchpadPreferences {
                    tap: Some(false),
                    ..Default::default()
                },
            },
            PointerDeviceRule {
                selector: InputDeviceSelector::Touchpad,
                preferences: TouchpadPreferences {
                    tap: Some(true),
                    tap_button_map: Some(FingerButtonMap::LeftRightMiddle),
                    ..Default::default()
                },
            },
            PointerDeviceRule {
                selector: InputDeviceSelector::All,
                preferences: TouchpadPreferences {
                    tap: Some(false),
                    click_method: Some(TouchpadClickMethod::Clickfinger),
                    ..Default::default()
                },
            },
        ]);
        assert_eq!(
            settings.resolve("pad", true),
            TouchpadPreferences {
                tap: Some(false),
                tap_button_map: Some(FingerButtonMap::LeftRightMiddle),
                click_method: Some(TouchpadClickMethod::Clickfinger),
            }
        );
        assert_eq!(settings.resolve("other", true).tap, Some(true));
        assert_eq!(settings.resolve("mouse", false).tap_button_map, None);
        assert_eq!(
            PointerDeviceSettings::default().resolve("pad", true),
            TouchpadPreferences::default()
        );
    }
}
/// Modifier requirements for a shell-owned pointer shortcut.
#[derive(Clone, Copy, Debug, Default, Eq, Hash, PartialEq)]
pub struct PointerShortcutModifiers {
    pub control: bool,
    pub alt: bool,
    pub shift: bool,
    pub super_key: bool,
}

impl PointerShortcutModifiers {
    /// Require the compositor Super modifier.
    pub const fn super_key() -> Self {
        Self {
            super_key: true,
            control: false,
            alt: false,
            shift: false,
        }
    }
}

/// A physical Linux key identity and modifiers, without toolkit key enums.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct Shortcut {
    pub trigger: Option<u32>,
    pub modifiers: PointerShortcutModifiers,
}
